#!/usr/bin/env node
/* Builds content.th.js from "Thai Content.md" (same labels as English Content.md, Thai values).
   Each Thai string is stored with the English it translates; the app uses it only while that
   English is unchanged, so a later English edit falls back to English instead of showing stale Thai.
   Run by tools/bump.py on every version bump. */
var fs = require('fs'), path = require('path');
var root = path.dirname(__dirname);
global.window = {};
require(path.join(root, 'content.js'));
var D = window.PORTFOLIO;
var md = fs.readFileSync(path.join(root, 'Thai Content.md'), 'utf8').split(/\r?\n/);
var secs = {}, cur = null, lab = null;
md.forEach(function (ln) {
  var m;
  if ((m = /^## (.+)$/.exec(ln))) { var k = /^Page (\d+)/.exec(m[1]); cur = secs[k ? 'p' + k[1] : m[1]] = {}; lab = null; return; }
  if (!cur) return;
  if ((m = /^\*\*([^*]+?):\*\*\s*(.*)$/.exec(ln))) { if (m[2] === '') { cur[m[1]] = []; lab = m[1]; } else { cur[m[1]] = m[2]; lab = null; } return; }
  if (lab && (m = /^- (.*)$/.exec(ln))) cur[lab].push(m[1]);
});
var out = [], miss = [];
function en(v) { return typeof v === 'string' ? v : null; }   /* objects already carry their own Thai */
function one(S, label, p, v, pg) { var e = en(v); if (e == null || e === '') return; var t = S[label];
  if (typeof t !== 'string') { miss.push(pg + ' ' + label); return; } if (t !== e) out.push([p, e, t]); }
function list(S, label, p, a, pg) { if (!a) return; var t = S[label];
  if (!Array.isArray(t) || t.length !== a.length) { miss.push(pg + ' ' + label + ' (list length)'); return; }
  a.forEach(function (x, i) { var e = en(x); if (e != null && t[i] !== e) out.push([p.concat(i), e, t[i]]); }); }
function items(S, pre, p, a, pg) { (a || []).forEach(function (it, i) { ['name', 'meta', 'text'].forEach(function (k) { one(S, pre + ' item ' + (i + 1) + ' ' + k, p.concat(i, k), it[k], pg); }); }); }
function col(S, pre, p, c, pg) { if (!c) return; one(S, pre + ' heading', p.concat('heading'), c.heading, pg); items(S, pre, p.concat('items'), c.items, pg);
  list(S, pre + ' list', p.concat('list'), c.list, pg);
  if (c.sub) { one(S, pre + ' lower heading', p.concat('sub', 'heading'), c.sub.heading, pg); items(S, pre + ' lower', p.concat('sub', 'items'), c.sub.items, pg); } }
D.pages.forEach(function (pgO, n) {
  var S = secs['p' + (n + 1)] || {}, P = ['pages', n], pg = 'Page ' + (n + 1) + ':';
  one(S, 'title', P.concat('title'), pgO.title, pg);
  if (pgO.type === 'project') { one(S, 'subtitle', P.concat('sub'), pgO.sub, pg); one(S, 'role', P.concat('role'), pgO.role, pg);
    list(S, 'problem', P.concat('problem'), pgO.problem, pg); list(S, 'solutions', P.concat('bullets'), pgO.bullets, pg); }
  if (pgO.type === 'research') { col(S, 'left', P.concat('left'), pgO.left, pg); col(S, 'right', P.concat('right'), pgO.right, pg); }
  if (pgO.type === 'cv') { one(S, 'statement', P.concat('statement'), pgO.statement, pg);
    (pgO.blocks || []).forEach(function (b, bi) { var pre = 'block ' + (bi + 1), B = P.concat('blocks', bi);
      one(S, pre + ' heading', B.concat('heading'), b.heading, pg);
      (b.entries || []).forEach(function (e, ei) { one(S, pre + ' entry ' + (ei + 1) + ' line1', B.concat('entries', ei, 't'), e.t, pg); one(S, pre + ' entry ' + (ei + 1) + ' line2', B.concat('entries', ei, 's'), e.s, pg); one(S, pre + ' entry ' + (ei + 1) + ' note', B.concat('entries', ei, 'n'), e.n, pg); });
      list(S, pre + ' list', B.concat('list'), b.list, pg); }); }
  if (pgO.type === 'gallery') (pgO.items || []).forEach(function (it, i) { one(S, 'item ' + (i + 1) + ' caption', P.concat('items', i, 'cap'), it.cap, pg); });
  (pgO.media || []).forEach(function (m, i) { one(S, 'media ' + (i + 1) + ' caption', P.concat('media', i, 'cap'), m.cap, pg); });
});
var js = '/* GENERATED by tools/thai_md.js from "Thai Content.md". Do not edit by hand. */\n' +
  '(function () {\n  var D = window.PORTFOLIO, T = ' + JSON.stringify(out).replace(/\],\[\[/g, '],\n    [[') + ';\n' +
  '  T.forEach(function (r) {\n    var o = D, p = r[0], k = p[p.length - 1];\n    for (var i = 0; i < p.length - 1; i++) { o = o && o[p[i]]; }\n' +
  '    if (o && o[k] === r[1]) o[k] = { en: r[1], th: r[2] };\n  });\n})();\n';
fs.writeFileSync(path.join(root, 'content.th.js'), js, 'utf8');
console.log('content.th.js written: ' + out.length + ' Thai strings' + (miss.length ? '; NOT TRANSLATED (English shown): ' + miss.join(' | ') : ''));
